let novoValor = Math.PI;

console.log(novoValor);

// .round() sempre arredonda pra um inteiro. maior ou igual a 0.5, arredonda pra cima. Se n pra baixo.
console.log(Math.round(novoValor));

// .floor() sempre arredonda pra baixo
console.log(Math.floor(3.75));

// .ceil() sempre arredonda pra cima
console.log(Math.ceil(3.1));

// .random() gera um número aleatório
console.log(Math.random());
